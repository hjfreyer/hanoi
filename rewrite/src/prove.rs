fn check_all(
    library: &Library,
    prog: &Program,
    files: &[ProvenFile],
    inline: &Tactic,
    opts: &Options,
    out: &mut dyn std::io::Write,
) -> std::io::Result<i32> {
    let mut selected = Vec::new();
    let mut filtered = 0usize;
    for file in files {
        for (identity, proof) in &file.pairs {
            let wanted = match &opts.filter {
                Some(sub) => library.identities[*identity].name.contains(sub),
                None => true,
            };
            if wanted {
                selected.push((file, *identity, *proof));
            } else {
                filtered += 1;
            }
        }
    }

    writeln!(
        out,
        "Proving {}...",
        plural(selected.len(), "identity", "identities")
    )?;

    let mut passed = 0usize;
    let mut failed = 0usize;
    for (file, index, proof) in &selected {
        let identity = &library.identities[*index];
        write!(out, "identity {} ... ", identity.name)?;
        match check(prog, identity, file, *proof, inline, opts) {
            Ok(proven) => {
                passed += 1;
                writeln!(out, "ok ({})", proven.closed.summary())?;
                if opts.show_script {
                    writeln!(out)?;
                    for line in derivation(prog, &proven) {
                        writeln!(out, "{}", line)?;
                    }
                    writeln!(out)?;
                }
            }
            Err(failure) => {
                failed += 1;
                writeln!(out, "FAILED")?;
                writeln!(out)?;
                for line in failure.render(prog, identity, file, *proof, opts) {
                    writeln!(out, "{}", line)?;
                }
                writeln!(out)?;
            }
        }
    }

    writeln!(out)?;
    writeln!(
        out,
        "identity result: {}. {} passed; {} failed; {} filtered out",
        if failed == 0 { "ok" } else { "FAILED" },
        passed,
        failed,
        filtered
    )?;
    Ok(if failed == 0 { OK } else { FAILED })
}

/// Why an identity did not come out proved.
enum Failure {
    /// A side the equations cannot speak about at all.
    Side(Precondition, &'static str, String),
    /// The proof expression does not resolve.
    Proof(String),
    /// The tactic ran out of fuel, was refused, or failed.
    ///
    /// Boxed, as is its sibling below: a `TacticError` carries the last two
    /// dozen steps of a run that would not settle, which is exactly what a
    /// reader wants and is far too much to widen every `Result` in this file by.
    Ran(Box<TacticError>),
    /// Inlining one side to compare them ran out of fuel. Named separately from
    /// `Ran`, since it is not the proof's own failure and reads as one.
    Inlining(&'static str, Box<TacticError>),
    /// An aimed step matched nothing.
    Missed(Vec<String>),
    /// It ran, and landed somewhere else.
    NotReached(Vec<Node>),
    /// The script does not reproduce the run. A bug here, not in the proof.
    Replay(String),
}

/// A discharged claim: the derivation, and how it closed.
struct Proven {
    /// The whole thing, `LHS ⇒ RHS`.
    script: Script,
    /// How it got there, which is what a listing has to say.
    closed: Closed,
}

/// The two ways a proof reaches the right-hand side.
enum Closed {
    /// The tactic landed on it as written. The derivation is the proof's own
    /// steps and nothing else.
    Exactly { steps: usize },
    /// It landed somewhere the right-hand side *inlines to*. Unfolding is an
    /// equation like any other — the axiom the library contributes by defining
    /// a sentence — so two terms with the same fully inlined form are equal.
    UpToInlining {
        /// The proof's own steps.
        steps: usize,
        /// Inlining what the proof reached.
        unfolded: usize,
        /// Folding the right-hand side back up, which is the *forward* unfold
        /// of the right-hand side read backwards.
        folded: usize,
    },
}

impl Closed {
    /// The count a passing line reports.
    fn summary(&self) -> String {
        match self {
            Closed::Exactly { steps } => plural(*steps, "step", "steps"),
            Closed::UpToInlining {
                steps,
                unfolded,
                folded,
            } => format!(
                "{} + {} up to inlining",
                plural(*steps, "step", "steps"),
                unfolded + folded
            ),
        }
    }
}

/// Runs one proof, returning its derivation.
fn check(
    prog: &Program,
    identity: &Identity,
    file: &ProvenFile,
    proof: usize,
    inline: &Tactic,
    opts: &Options,
) -> Result<Proven, Failure> {
    // Both sides, not only the one that gets rewritten: the right-hand side is
    // the term the claim is measured against, so it has to be one the equations
    // can speak about too. It is also what makes the inlining below terminate,
    // since `#[recursive]` is refused and that property is closed over
    // reachability.
    for (side, which) in [(identity.lhs, "left-hand"), (identity.rhs, "right-hand")] {
        if let Err(p) = check_preconditions(prog, side) {
            return Err(Failure::Side(p, which, prog.library().names[side].clone()));
        }
    }

    let tactic = compile(prog, file, proof)?;
    let lhs = tree(prog, identity.lhs);
    let rhs = tree(prog, identity.rhs);

    let env = Env::new(prog, opts.fuel, opts.check);
    let (got, s1) =
        run_tactic(&env, &tactic, lhs.clone()).map_err(|e| Failure::Ran(Box::new(e)))?;

    let misses = env.misses();
    if !misses.is_empty() {
        return Err(Failure::Missed(miss_report(&misses)));
    }

    // The claim that makes a script a derivation rather than a log: replaying
    // it against a fresh build reproduces the run *exactly*. Checked here on
    // the proof's own steps, where `==` is available and is the stronger
    // comparison — the end of the whole derivation is measured by effect.
    let mut replayed = lhs.clone();
    match apply_script(prog, &mut replayed, &s1, opts.check) {
        Ok(()) if replayed == got => {}
        Ok(()) => return Err(Failure::Replay("it produced a different tree".to_string())),
        Err(err) => return Err(Failure::Replay(err.to_string())),
    }

    let steps = s1.len();
    // Compared by effect, not by `==`. Phase 4 mints a fresh `SentenceIndex`
    // for every inline block, so the right-hand side's blocks can never share
    // provenance with anything the left-hand side rewrote into — and provenance
    // is not part of a term's identity.
    let (script, closed) = if same_effect_seq(&got, &rhs) {
        (s1, Closed::Exactly { steps })
    } else {
        // Up to inlining. The fold-back is generated by running the *forward*
        // unfold on the right-hand side and inverting the script — which is why
        // `inv(unfold)` having no matcher costs nothing here. Nothing can read a
        // window and say which sentence to fold into, and nothing has to: the
        // step already names it.
        let (left, s2) = normalize(prog, inline, got.clone(), "left-hand", opts)?;
        let (right, s3) = normalize(prog, inline, rhs.clone(), "right-hand", opts)?;
        if !same_effect_seq(&left, &right) {
            return Err(Failure::NotReached(got));
        }
        let (unfolded, folded) = (s2.len(), s3.len());
        let mut script = s1;
        script.extend(s2);
        script.extend(invert(&s3));
        (
            script,
            Closed::UpToInlining {
                steps,
                unfolded,
                folded,
            },
        )
    };

    // And the derivation ends at the right-hand side. That is the thing the old
    // one-sided check could not say: its script stopped at what the tactic
    // reached, and the last hop was an equality test rather than a splice the
    // applier had to accept.
    let mut landed = lhs;
    match apply_script(prog, &mut landed, &script, opts.check) {
        Ok(()) if same_effect_seq(&landed, &rhs) => Ok(Proven { script, closed }),
        Ok(()) => Err(Failure::Replay(
            "it did not land on the right-hand side".to_string(),
        )),
        Err(err) => Err(Failure::Replay(err.to_string())),
    }
}

/// Inlines every call, and says which side it was doing it to.
///
/// A separate `Env` per side, so the two scripts stay separable — the left's is
/// appended and the right's is inverted. Neither can record a miss: `unfold_all`
/// aims at nothing.
fn normalize(
    prog: &Program,
    inline: &Tactic,
    nodes: Vec<Node>,
    which: &'static str,
    opts: &Options,
) -> Result<(Vec<Node>, Script), Failure> {
    let env = Env::new(prog, opts.fuel, opts.check);
    run_tactic(&env, inline, nodes).map_err(|e| Failure::Inlining(which, Box::new(e)))
}

fn compile(prog: &Program, file: &ProvenFile, proof: usize) -> Result<Tactic, Failure> {
    file.file
        .compile(&file.file.proofs[proof], prog)
        .map_err(|e| Failure::Proof(e.render_in(&file.source, &file.hant.display().to_string())))
}

fn tree(prog: &Program, root: SentenceIndex) -> Vec<Node> {
    build(prog.library(), root, &mut HashSet::new())
}

impl Failure {
    fn render(
        &self,
        prog: &Program,
        identity: &Identity,
        file: &ProvenFile,
        proof: usize,
        opts: &Options,
    ) -> Vec<String> {
        let mut out = Vec::new();
        match self {
            Failure::Side(p, which, name) => {
                let lines = precondition_explanation(*p, name);
                out.push(format!("  the {} side cannot be rewritten.", which));
                out.push(String::new());
                out.push(format!("  {}", lines[0]));
                out.extend(lines[1..].iter().cloned());
            }
            Failure::Proof(rendered) => {
                out.push("  the proof does not compile.".to_string());
                out.push(String::new());
                out.extend(rendered.lines().map(|l| l.to_string()));
            }
            Failure::Ran(err) => {
                out.push(format!("  the proof did not run: {}", err));
                out.extend(cited(file, proof));
            }
            Failure::Inlining(which, err) => {
                out.push(format!(
                    "  the proof ran, but inlining the {} side to compare them",
                    which
                ));
                out.push(format!("  did not finish: {}", err));
                out.push(String::new());
                out.push(
                    "  The two sides are compared up to inlining, so both are unfolded".to_string(),
                );
                out.push(
                    "  when the proof does not land on the right-hand side as written.".to_string(),
                );
                out.extend(cited(file, proof));
            }
            Failure::Missed(report) => {
                out.push("  an aimed step in the proof matched nothing.".to_string());
                out.push(String::new());
                out.extend(report.iter().map(|l| indented(l)));
                out.push(String::new());
                out.push(
                    "  Here that fails the proof rather than warning: a proof aimed at a"
                        .to_string(),
                );
                out.push(
                    "  tree it no longer describes is wrong even where the goal was reached."
                        .to_string(),
                );
                out.extend(cited(file, proof));
            }
            Failure::NotReached(got) => {
                out.push("  the proof ran, but did not reach the right-hand side,".to_string());
                out.push("  and inlining both sides did not reconcile them either.".to_string());
                out.extend(cited(file, proof));
                out.push(String::new());
                let want = tree(prog, identity.rhs);
                // Without origins: the two sides came from two sentences, so
                // every `<inline>` label differs and none of the differences
                // mean anything. `same_effect_seq` ignores them for the same
                // reason, and a listing being compared has to agree with the
                // comparison.
                let left = render_nodes(prog, got, opts.stack, true, false);
                let right = render_nodes(prog, &want, opts.stack, true, false);
                let rows = side_by_side(&left, &right, "what it reached", "the right-hand side");
                if rows.is_empty() {
                    // Two listings that read alike but are not the same by
                    // effect. That is a bug in one of them rather than in the
                    // proof, so show both rather than nothing at all.
                    out.push(
                        "  The two listings read alike but are not the same term.".to_string(),
                    );
                    out.extend(left);
                    out.push(String::new());
                    out.extend(right);
                } else {
                    out.extend(rows);
                }
                // The listing above is what is *written*, which is the useful
                // orientation. When the difference is inside a call, the way to
                // see it is to open the two sides up — and each is addressable
                // by name, which is what that naming is for.
                out.push(String::new());
                out.push(format!(
                    "  To see inside the calls: rewrite <dir> '{}::lhs' -t unfold_all",
                    short_path(&identity.name)
                ));
                out.push("  and the same for `::rhs`.".to_string());
            }
            Failure::Replay(why) => {
                out.push("  the proof reached the right-hand side, but its derivation".to_string());
                out.push(format!("  does not replay: {}", why));
                out.push(String::new());
                out.push("  That is a bug in the rewriter, not in the proof.".to_string());
            }
        }
        out
    }
}

/// The derivation, in the segments it was built from.
///
/// A proof that closed exactly has one. A proof that closed up to inlining has
/// three, and saying which is which matters: a reader looking at a hundred
/// unfolds followed by a hundred folds is owed an explanation of why the term
/// went somewhere and came back.
fn derivation(prog: &Program, proven: &Proven) -> Vec<String> {
    match proven.closed {
        Closed::Exactly { .. } => crate::derivation_lines(prog, "derivation", &proven.script),
        Closed::UpToInlining {
            steps,
            unfolded,
            folded,
        } => {
            let (a, rest) = proven.script.split_at(steps);
            let (b, c) = rest.split_at(unfolded);
            debug_assert_eq!(c.len(), folded);
            let mut out = crate::derivation_lines(prog, "the proof", a);
            out.push(String::new());
            out.extend(crate::derivation_lines(prog, "inlining what it reached", b));
            out.push(String::new());
            out.extend(crate::derivation_lines(
                prog,
                "folding the right-hand side back up",
                c,
            ));
            out
        }
    }
}

/// The proof as written, and where. What a reader needs to go and fix it.
fn cited(file: &ProvenFile, proof: usize) -> Vec<String> {
    let def = &file.file.proofs[proof];
    let (start, end) = def.span;
    let text = file.source[start..end.min(file.source.len())].trim();
    let line = file.source[..start].matches('\n').count() + 1;
    vec![
        String::new(),
        format!("  proof: {}", text),
        format!("   --> {}:{}", file.hant.display(), line),
    ]
}

/// Two spaces in front of a line, except an empty one — which would otherwise
/// become trailing whitespace in the report.
fn indented(line: &str) -> String {
    if line.is_empty() {
        String::new()
    } else {
        format!("  {}", line)
    }
}

/// Enough of a name to be unambiguous on the command line, which is the
/// trailing segment — the reading `resolve_sentence` gives.
fn short_path(name: &str) -> &str {
    name.rsplit("::").next().unwrap_or(name)
}

fn short(name: &str) -> &str {
    name.rsplit("::").next().unwrap_or(name)
}

fn plural(n: usize, one: &str, many: &str) -> String {
    if n == 1 {
        format!("{} {}", n, one)
    } else {
        format!("{} {}", n, many)
    }
}

