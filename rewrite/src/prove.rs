//! Checking that every identity a corpus states has a proof that discharges it.
//!
//! `.hana` states the claim, the sibling `.hant` proves it, and this walks the
//! two together. What it is for is that a claim should be worth something:
//! `rewrite` can show two programs are interchangeable, but the showing was
//! printed and lost, so nothing re-checked it when the library changed
//! underneath.
//!
//! **A proof is one-sided, and the comparison is up to inlining.** The tactic
//! rewrites the left-hand side; the result must be the right-hand side, either
//! as written or after both are unfolded. Every step is an equation, so what
//! the run leaves behind is a derivation LHS ⇒ RHS — one linear script, which
//! is a thing that can be replayed, printed, stepped through and diffed.
//!
//! Unfolding being an equation like any other is what makes the second reading
//! sound: it is the axiom the library contributes by defining a sentence, so
//! two terms with the same fully inlined form are equal. The fold-back is
//! generated by running the *forward* unfold on the right-hand side and
//! inverting the script — which is why `inv(unfold)` having no matcher costs
//! nothing. Nothing can read a window and say which sentence to fold into, and
//! nothing has to: the step already names it.
//!
//! So the derivation **ends at the right-hand side**, and the replay says so.
//! That is what the comparison alone could not: a script that stopped at what
//! the tactic reached left the last hop an equality test rather than a splice
//! the applier had to accept.
//!
//! Two things here deliberately differ from `rewrite`, and both are the same
//! difference: `rewrite` explores, and this decides.
//!
//! - **A miss fails a proof**, where in `rewrite` it is a diagnostic that still
//!   prints the tree. `at(9, sink)` in a proof is a claim that there is
//!   something at 9; when there is not, the proof is written against a tree it
//!   no longer describes, even if the goal was reached anyway.
//! - **`--check` is on by default.** In `rewrite` it is opt-in because the
//!   listing is the answer and the check only costs time. Here the answer is
//!   *yes* or *no*, and a wrong yes is worse than a slow run.

